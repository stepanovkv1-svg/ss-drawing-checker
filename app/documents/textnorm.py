"""Нормализация обозначений для сравнения (итог Э0, И3/И8): похожие латинские и кириллические
буквы, виды тире, пробелы. Исходный текст не меняется — нормализованный используется только для сравнения."""
from __future__ import annotations

import re

_LAT_TO_CYR = str.maketrans({
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К", "M": "М", "O": "О", "P": "Р", "T": "Т",
    "X": "Х", "Y": "У", "a": "а", "c": "с", "e": "е", "o": "о", "p": "р", "x": "х", "y": "у",
})
_DASHES = re.compile(r"[‐‑‒–—−]")


def has_cyrillic(s: str) -> bool:
    return bool(re.search(r"[А-Яа-яЁё]", s))


def norm_code(s: str) -> str:
    """Обозначение (ККС-47, НСС-02, шифр): верхний регистр, кириллица вместо похожей латиницы,
    одно тире, без пробелов вокруг тире и по краям."""
    s = _DASHES.sub("-", s.strip())
    s = re.sub(r"\s*-\s*", "-", s)
    s = re.sub(r"\s+", " ", s)
    return s.upper().translate(_LAT_TO_CYR)


def norm_text(s: str) -> str:
    """Свободный текст: одинарные пробелы, ё→е, без учёта регистра."""
    s = _DASHES.sub("-", s)
    return re.sub(r"\s+", " ", s).strip().lower().replace("ё", "е")
